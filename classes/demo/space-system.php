<script>
  (() => {
    const demo = document.getElementById("spaceDemo");
    const range = demo.querySelector("#spaceRange");
    const label = demo.querySelector("#spaceLabel");
    const wrapper = demo.querySelector("#spaceWrapper");

    function updateSpacing() {
      const width = parseInt(range.value);

      // ✅ Resize container
      wrapper.style.width = width + "px";

      // ✅ Breakpoint logic
      let unit, mode;

      if (width < 770) {
        unit = 4;
        mode = "Mobile";
      } else if (width < 990) {
        unit = 6;
        mode = "Tablet";
      } else {
        unit = 8;
        mode = "Desktop";
      }

      label.textContent = mode + " · " + unit + "px";

      // ✅ update local variables
      demo.style.setProperty("--space-unit", unit + "px");

    }

    range.addEventListener("input", updateSpacing);

    updateSpacing();
  })();
</script>